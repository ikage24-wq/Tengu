#!/usr/bin/env python3
"""Builds the effect sprite strips in assets/fx/ and the list the game reads
(src/render/fx-sheets.js) from Tengu's own effect art: tools/fx-art.js, drawn in the browser and
matched to the sprites by tools/draw-fx.cjs. Each effect's frames are trimmed to the box they all
share and laid out as one horizontal strip (the `cel*` strips).

Usage: python3 tools/build-fx.py   (needs Pillow and Playwright)
"""

import json
import os
import subprocess
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cel_frames():
    # Tengu's own effect art (tools/fx-art.js), drawn by tools/draw-fx.cjs in the browser.
    tmp = tempfile.mkdtemp()
    subprocess.run(['node', os.path.join(ROOT, 'tools', 'draw-fx.cjs'), tmp], check=True)
    meta = json.load(open(os.path.join(tmp, 'meta.json')))
    frames = {n: [Image.open(os.path.join(tmp, n, f'{i}.png')).convert('RGBA') for i in range(m['n'])] for n, m in meta.items()}
    return frames, meta


def build():
    out_dir = os.path.join(ROOT, 'assets', 'fx')
    os.makedirs(out_dir, exist_ok=True)
    sheets = {}
    cel, cel_meta = cel_frames()
    for effect, m in cel_meta.items():
        name = 'cel' + effect
        frames = [f for f in cel[effect] if f.getbbox()]
        boxes = [f.getbbox() for f in frames]
        x0 = min(b[0] for b in boxes)
        y0 = min(b[1] for b in boxes)
        x1 = max(b[2] for b in boxes)
        y1 = max(b[3] for b in boxes)
        w, h = x1 - x0, y1 - y0
        strip = Image.new('RGBA', (w * len(frames), h), (0, 0, 0, 0))
        for i, f in enumerate(frames):
            strip.paste(f.crop((x0, y0, x1, y1)), (i * w, 0))
        strip.save(os.path.join(out_dir, f'{name}.png'), optimize=True)
        swing = m['swing'] and [round(m['swing'][0], 3), m['swing'][1], m['swing'][2]]
        sheets[name] = {'w': w, 'h': h, 'n': len(frames), 'fps': m['fps'], 'px': round(m['px'] - x0), 'py': round(m['py'] - y0), 'loop': m['loop'], 'swing': swing}
        print(f'{name:10s} {len(frames):3d} frames {w}x{h}')
    lines = ['// Generated by tools/build-fx.py: the effect sprite strips in assets/fx/ (Tengu\'s own effect',
             '// art, tools/fx-art.js). Each strip is `n` frames of w x h laid side by side, played at `fps`;',
             '// (px, py) is the point in a frame that sits on the effect\'s position. A swipe\'s r, mid and',
             '// turn are its radius, the angle of its sweep\'s middle and which way it sweeps (1 clockwise),',
             '// so it can be laid along a blade\'s swing.',
             '', 'export const FX_SHEETS = {']
    for name, s in sheets.items():
        extra = ''
        if s.get('swing'):
            extra += f", r: {s['swing'][2]}, mid: {s['swing'][0]}, turn: {s['swing'][1]}"
        lines.append(f"  {name}: {{ w: {s['w']}, h: {s['h']}, n: {s['n']}, fps: {s['fps']}, px: {s['px']}, py: {s['py']}, loop: {str(s['loop']).lower()}{extra} }},")
    lines.append('};')
    open(os.path.join(ROOT, 'src', 'render', 'fx-sheets.js'), 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    build()
